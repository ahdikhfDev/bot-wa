import { generateVideo, generateKonten, isVideoJobRunning, cleanup } from '../services/videoGenerator.js';

const VALID_STYLES = ['edukasi', 'fakta', 'story', 'quotes'];

let lastVideoPath = null;

export function getLastVideoPath() {
    return lastVideoPath;
}

export default {
    name: 'video',
    title: 'Buat Video & Konten',
    description: 'Generate video/konten dari topik via AI + Pollinations + Edge-TTS natural + FFmpeg',
    commands: ['buatvideo', 'bv', 'video', 'konten'],

    async handler(sock, remoteJid, args, context) {
        const { command } = context;
        const isKonten = command === 'konten';

        if (args.length === 0) {
            const usage = isKonten
                ? `📱 *Konten Cepet*\nBuat konten singkat (gambar + suara natural) dalam hitungan detik.\n\n*Cara pakai:*\n/konten [style] [topik]\n/konten fakta kenapa langit biru\n/konten quotes motivasi hidup\n/konten edukasi cara kerja ChatGPT\n/konten story kisah inspiratif\n\n*Style:* fakta, quotes, edukasi, story`
                : `🎬 *Buat Video*\nBuat video otomatis dengan video Pexels + suara natural + subtitle.\n\n*Cara pakai:*\n/buatvideo [style] [topik]\n/buatvideo edukasi cara kerja AI\n/buatvideo fakta unik tentang kucing\n/buatvideo story legenda Indonesia\n/buatvideo quotes kata bijak hari ini\n/buatvideo roast [nama orang]\n\n*Style:* edukasi, fakta, story, quotes\n*Roasting:* /buatvideo roast [target]`;

            await sock.sendMessage(remoteJid, { text: usage });
            return;
        }

        if (isVideoJobRunning()) {
            await sock.sendMessage(remoteJid, {
                text: 'Masih ada video/konten yang sedang digenerate. Tunggu selesai dulu ya!'
            });
            return;
        }

        // Parse style dari argumen pertama
        let style = 'edukasi';
        let topicArgs = args;

        const firstArg = args[0].toLowerCase();
        if (VALID_STYLES.includes(firstArg)) {
            style = firstArg;
            topicArgs = args.slice(1);
        // Deteksi style dari command itu sendiri kalo pake alias
        } else if (isKonten) {
            // Default konten pake fakta kalo gak ada style
            style = 'fakta';
        }

        const topic = topicArgs.join(' ');
        if (!topic) {
            await sock.sendMessage(remoteJid, {
                text: `Masukkan topik setelah style.\nContoh: /${command} ${style} [topik]`
            });
            return;
        }

        let progressMsg = await sock.sendMessage(remoteJid, {
            text: isKonten
                ? `✨ *Bikin konten ${style}...*\nTopik: ${topic.substring(0, 100)}`
                : `🎬 *Bikin video ${style}...*\nTopik: ${topic.substring(0, 100)}`
        });

        try {
            let result;
            let caption;

            if (isKonten) {
                result = await generateKonten(topic, async (progress) => {
                    if (progressMsg?.key) {
                        progressMsg = await sock.sendMessage(remoteJid, { text: progress });
                    }
                }, style);
                caption = `${result.title}\n━━━━━━━━━━━━━━\n🎯 ${style.toUpperCase()}\n🤖 Generated by Thirty`;
            } else {
                result = await generateVideo(topic, async (progress) => {
                    if (progressMsg?.key) {
                        progressMsg = await sock.sendMessage(remoteJid, { text: progress });
                    }
                }, style);
                caption = result.title + '\n\n🎥 Generated by Thirty';
            }

            lastVideoPath = result.outputPath;

            await sock.sendMessage(remoteJid, {
                video: { url: result.outputPath },
                caption: caption
            });

            cleanup(result.workDir);
        } catch (err) {
            await sock.sendMessage(remoteJid, {
                text: '❌ Gagal: ' + err.message.substring(0, 300)
            });
        }
    }
};
